"""Native-tool configs for Python repos, generated from the reference's data and the repo.

Native engines stay native (plan §1.3); init only writes their configuration:

- ``ruff.toml`` from ``data/native-tools.json`` (the catalogue's RUFF.* values; the ``N``
  selection enforces the house-style Python casing), with ``target-version`` from
  ``project.requires-python`` and ``lint.isort.known-first-party`` from the repo's packages;
- ``mypy.ini`` from the same data (MYPY.*), with ``python_version``, ``packages`` and
  ``mypy_path`` from the repo;
- ``.importlinter`` with one layers contract from the profile's ``structure.tiers`` (lowest
  first) inside ``structure.import_direction.package``, once both are recorded.

A repo's packages are the top-level folders holding ``__init__.py`` at the repo root or under
``src/``. Init writes a config only where the tool has none: an existing ``ruff.toml``,
``.ruff.toml``, ``[tool.ruff]``, ``mypy.ini``, ``.mypy.ini``, ``[tool.mypy]``, setup.cfg
``[mypy]``, ``.importlinter`` or ``[tool.importlinter]`` is kept and reported, never replaced.
A value init cannot derive (no ``requires-python``, no package yet) leaves that config unwritten
and is reported, so a later run writes it once the repo has the value.
"""

from __future__ import annotations

import json
import re
import tomllib
from importlib import resources
from pathlib import Path

from omp_guardrails.config.profile import PLACEHOLDER

DATA_FILE = "native-tools.json"
HEADER = "# Generated by omp-guardrails init from its native-tool data; edit the values per ADR.\n"
REQUIRES = re.compile(r">=\s*(\d+)\.(\d+)")
SKIPPED = frozenset({"tests", "test", "docs", "build", "dist", "node_modules"})


def load_data() -> dict:
    data = resources.files("omp_guardrails.data").joinpath(DATA_FILE).read_text(encoding="utf-8")
    return json.loads(data)


def pyproject(repo: Path) -> dict:
    path = repo / "pyproject.toml"
    if not path.is_file():
        return {}
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return {}


def python_version(project: dict) -> tuple[int, int] | None:
    requires = project.get("project", {}).get("requires-python")
    match = REQUIRES.search(requires) if isinstance(requires, str) else None
    return (int(match.group(1)), int(match.group(2))) if match else None


def packages(repo: Path) -> tuple[list[str], list[str]]:
    """Top-level package names and the source roots that hold them."""
    names: list[str] = []
    roots: list[str] = []
    for root_name in (".", "src"):
        root = repo / root_name
        if not root.is_dir():
            continue
        found = sorted(
            child.name
            for child in root.iterdir()
            if child.is_dir()
            and (child / "__init__.py").is_file()
            and child.name not in SKIPPED
            and not child.name.startswith(".")
        )
        if found:
            names.extend(found)
            roots.append(root_name)
    return names, roots


def toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    return json.dumps(value)


def toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key)


def render_ruff(data: dict, version: tuple[int, int], first_party: list[str]) -> str:
    ruff = data["ruff"]
    lines = [HEADER.rstrip("\n"), f'target-version = "py{version[0]}{version[1]}"']
    lines.extend(f"{toml_key(key)} = {toml_value(value)}" for key, value in ruff["root"].items())
    for table, values in ruff.items():
        if table == "root":
            continue
        lines.extend(["", f"[{table}]"])
        if table == "lint.isort":
            lines.append(f"known-first-party = {toml_value(first_party)}")
        lines.extend(f"{toml_key(key)} = {toml_value(value)}" for key, value in values.items())
    return "\n".join(lines) + "\n"


def ini_value(value: object) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    return str(value)


def render_mypy(data: dict, version: tuple[int, int], names: list[str], roots: list[str]) -> str:
    lines = [HEADER.rstrip("\n"), "[mypy]", f"python_version = {version[0]}.{version[1]}"]
    lines.extend(f"{key} = {ini_value(value)}" for key, value in data["mypy"].items())
    lines.append(f"packages = {', '.join(names)}")
    lines.append(f"mypy_path = {', '.join(roots)}")
    return "\n".join(lines) + "\n"


def render_importlinter(package: str, tiers: list[str]) -> str:
    layers = "\n".join(f"    {tier}" for tier in reversed(tiers))
    return (
        f"{HEADER}[importlinter]\nroot_package = {package}\n\n"
        "[importlinter:contract:structure-tiers]\n"
        "name = structure.tiers: import only your own or a lower tier\n"
        f"type = layers\ncontainers =\n    {package}\nlayers =\n{layers}\n"
    )


def ini_has_section(path: Path, section: str) -> bool:
    if not path.is_file():
        return False
    text = path.read_text(encoding="utf-8", errors="replace")
    return re.search(rf"^\[{re.escape(section)}\]", text, re.MULTILINE) is not None


def existing(repo: Path, project: dict, tool: str) -> str | None:
    """Where the repo already configures ``tool``, or None."""
    files = {
        "ruff": ("ruff.toml", ".ruff.toml"),
        "mypy": ("mypy.ini", ".mypy.ini"),
        "importlinter": (".importlinter",),
    }[tool]
    for name in files:
        if (repo / name).is_file():
            return name
    if tool in project.get("tool", {}):
        return f"pyproject.toml [tool.{tool}]"
    if tool == "mypy" and ini_has_section(repo / "setup.cfg", "mypy"):
        return "setup.cfg [mypy]"
    return None


def real_text(value: object) -> bool:
    return isinstance(value, str) and bool(value.strip()) and not PLACEHOLDER.search(value)


def planned_configs(repo: Path, profile: dict) -> tuple[dict[str, str], list[str]]:
    """Files to write (path -> text) and report lines for the configs init leaves alone."""
    project = pyproject(repo)
    data = load_data()
    version = python_version(project)
    names, roots = packages(repo)
    planned: dict[str, str] = {}
    report: list[str] = []
    for tool, path in (("ruff", "ruff.toml"), ("mypy", "mypy.ini")):
        kept = existing(repo, project, tool)
        if kept:
            report.append(f"native: kept the existing {tool} configuration in {kept}")
        elif version is None:
            report.append(f"native: {tool} not written; set project.requires-python first")
        elif tool == "ruff":
            planned[path] = render_ruff(data, version, names)
        elif not names:
            report.append("native: mypy not written; the repo has no package with __init__.py")
        else:
            planned[path] = render_mypy(data, version, names, roots)
    structure = profile.get("structure") if isinstance(profile.get("structure"), dict) else {}
    direction = structure.get("import_direction")
    package = direction.get("package") if isinstance(direction, dict) else None
    tiers = structure.get("tiers") if isinstance(structure.get("tiers"), list) else []
    kept = existing(repo, project, "importlinter")
    if kept:
        report.append(f"native: kept the existing import-linter configuration in {kept}")
    elif real_text(package) and len(tiers) >= 2 and all(real_text(tier) for tier in tiers):
        planned[".importlinter"] = render_importlinter(package, tiers)
    else:
        report.append(
            "native: import-linter not written; record structure.tiers and "
            "structure.import_direction.package, then run init again"
        )
    return planned, report
